"""Customer progress + IR job-card status helpers."""

from app.modules.job_cards.models import JobCard

IR_STATUSES = {
    "INSPECTION_BOOKED",
    "INSPECTION_IN_PROGRESS",
    "ESTIMATE_PENDING",
    "REPAIR_APPROVAL_DUE",
    "PARTS_ADVANCE_DUE",
    "PARTS_PENDING",
    "REPAIR_BOOKING_REQUIRED",
    "REPAIR_BOOKED",
    "REPAIR_IN_PROGRESS",
}

PROGRESS_BY_STATUS = {
    "EDITABLE": "BUILDING",
    "READY_FOR_FINALIZATION": "BUILDING",
    "FINALIZATION_IN_PROGRESS": "BUILDING",
    "READY_TO_BOOK": "BUILDING",
    "INSPECTION_BOOKED": "BOOKING_CONFIRMED",
    "INSPECTION_IN_PROGRESS": "VISIT_IN_PROGRESS",
    "ESTIMATE_PENDING": "ESTIMATE_PENDING",
    "REPAIR_APPROVAL_DUE": "ESTIMATE_APPROVAL_REQUIRED",
    "PARTS_ADVANCE_DUE": "PARTS_PAYMENT_REQUIRED",
    "PARTS_PENDING": "REPAIR_BOOKING_REQUIRED",
    "REPAIR_BOOKING_REQUIRED": "REPAIR_BOOKING_REQUIRED",
    "REPAIR_BOOKED": "BOOKING_CONFIRMED",
    "REPAIR_IN_PROGRESS": "VISIT_IN_PROGRESS",
    "COMPLETED": "COMPLETED",
    "CANCELLED": "COMPLETED",
}


def customer_progress(job_card: JobCard) -> str:
    if job_card.flow_policy != "INSPECTION_REPAIR":
        if job_card.status == "BOOKING_CREATED":
            return "BOOKING_CONFIRMED"
        return "BUILDING"
    return PROGRESS_BY_STATUS.get(job_card.status, "BUILDING")
